"""
Member 4 — Crater Geometry Extraction.

Converts a detected crater candidate into a detailed
geometric description using radial DEM analysis.

This module is independent of Members 1, 2, 3 and 5.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from lunar_hazard_mapper.m3_terrain.dem import DEM

from .detector import CraterCandidate
from .profile import DEMProfileGenerator
from .types import (
    CraterCenter,
    CraterGeometry,
    DEMProfile,
)


@dataclass(frozen=True)
class ExtractedCraterGeometry:
    """
    Complete geometric description extracted from a DEM.
    """

    center: CraterCenter

    geometry: CraterGeometry

    dem_profile: DEMProfile


class CraterGeometryExtractor:
    """
    Extract detailed crater geometry from a DEM.

    The radial DEM profile is generated by the shared
    DEMProfileGenerator component.
    """

    def __init__(
        self,
        max_radius_m: float = 100.0,
        radial_step_m: float = 1.0,
        angular_samples: int = 72,
    ) -> None:

        if max_radius_m <= 0:
            raise ValueError(
                "max_radius_m must be positive."
            )

        if radial_step_m <= 0:
            raise ValueError(
                "radial_step_m must be positive."
            )

        if angular_samples < 8:
            raise ValueError(
                "angular_samples must be at least 8."
            )

        self.max_radius_m = max_radius_m
        self.radial_step_m = radial_step_m
        self.angular_samples = angular_samples

    def extract(
        self,
        dem: DEM,
        candidate: CraterCandidate,
    ) -> ExtractedCraterGeometry:
        """
        Extract crater geometry around a detected candidate.
        """

        elevation = np.asarray(
            dem.elevation,
            dtype=float,
        )

        pixel_size = float(
            dem.pixel_size_m
        )

        rows, cols = elevation.shape

        # Candidate coordinates are stored in metres.
        center_col = (
            candidate.center_x_m
            / pixel_size
        )

        center_row = (
            candidate.center_y_m
            / pixel_size
        )

        # --------------------------------------------------
        # Generate radial DEM profile
        # --------------------------------------------------

        profile_generator = DEMProfileGenerator(
            max_radius_m=self.max_radius_m,
            radial_step_m=self.radial_step_m,
            angular_samples=self.angular_samples,
        )

        dem_profile = profile_generator.generate(
            dem=dem,
            center_x_m=candidate.center_x_m,
            center_y_m=candidate.center_y_m,
        )

        radii = np.asarray(
            dem_profile.distances_m,
            dtype=float,
        )

        profile = np.asarray(
            dem_profile.elevations_m,
            dtype=float,
        )

        if len(profile) < 3:
            raise ValueError(
                "Insufficient DEM samples for "
                "crater geometry extraction."
            )

        # --------------------------------------------------
        # Estimate surrounding terrain
        # --------------------------------------------------

        outer_count = max(
            3,
            len(profile) // 5,
        )

        outer_profile = profile[
            -outer_count:
        ]

        surrounding_elevation = float(
            np.median(
                outer_profile
            )
        )

        # --------------------------------------------------
        # Estimate crater depth
        # --------------------------------------------------

        minimum_index = int(
            np.argmin(profile)
        )

        minimum_elevation = float(
            profile[minimum_index]
        )

        depth_m = max(
            0.0,
            surrounding_elevation
            - minimum_elevation,
        )

        # --------------------------------------------------
        # Estimate crater rim
        # --------------------------------------------------

        rim_index = self._estimate_rim_index(
            profile,
            surrounding_elevation,
            minimum_index,
        )

        radius_m = float(
            radii[rim_index]
        )

        if radius_m <= 0:
            radius_m = max(
                candidate.radius_m,
                pixel_size,
            )

        # --------------------------------------------------
        # Estimate circularity
        # --------------------------------------------------

        circularity = self._estimate_circularity(
            elevation,
            center_row,
            center_col,
            radius_m,
            pixel_size,
        )

        # --------------------------------------------------
        # Estimate rim height
        # --------------------------------------------------

        rim_window_start = max(
            0,
            rim_index - 2,
        )

        rim_window_end = min(
            len(profile),
            rim_index + 3,
        )

        rim_elevation = float(
            np.median(
                profile[
                    rim_window_start:
                    rim_window_end
                ]
            )
        )

        rim_height_m = max(
            0.0,
            rim_elevation
            - surrounding_elevation,
        )

        # --------------------------------------------------
        # Create M4 scientific contracts
        # --------------------------------------------------

        center = CraterCenter(
            x_m=float(
                candidate.center_x_m
            ),
            y_m=float(
                candidate.center_y_m
            ),
        )

        geometry = CraterGeometry(
            diameter_m=float(
                2.0 * radius_m
            ),
            radius_m=float(
                radius_m
            ),
            depth_m=float(
                depth_m
            ),
            circularity=float(
                circularity
            ),
            rim_height_m=float(
                rim_height_m
            ),
        )

        return ExtractedCraterGeometry(
            center=center,
            geometry=geometry,
            dem_profile=dem_profile,
        )

    @staticmethod
    def _estimate_rim_index(
        profile: np.ndarray,
        surrounding_elevation: float,
        minimum_index: int,
    ) -> int:
        """
        Estimate the crater rim from the radial profile.

        The rim is selected near the first strong recovery
        toward the surrounding terrain after the depression.
        """

        if minimum_index >= len(profile) - 1:
            return minimum_index

        minimum_elevation = float(
            profile[minimum_index]
        )

        total_recovery = (
            surrounding_elevation
            - minimum_elevation
        )

        if total_recovery <= 0:
            return minimum_index

        target = (
            minimum_elevation
            + 0.80 * total_recovery
        )

        for index in range(
            minimum_index + 1,
            len(profile),
        ):

            if profile[index] >= target:
                return index

        return len(profile) - 1

    @staticmethod
    def _estimate_circularity(
        elevation: np.ndarray,
        center_row: float,
        center_col: float,
        radius_m: float,
        pixel_size_m: float,
    ) -> float:
        """
        Estimate circularity from radial boundary consistency.

        Values close to 1 indicate a more circular structure.
        """

        radius_px = (
            radius_m / pixel_size_m
        )

        rows, cols = elevation.shape

        radii = []

        for angle in np.linspace(
            0.0,
            2.0 * np.pi,
            72,
            endpoint=False,
        ):

            test_radius = radius_px

            for scale in np.linspace(
                0.75,
                1.25,
                20,
            ):

                candidate_radius = (
                    radius_px * scale
                )

                row = (
                    center_row
                    + candidate_radius
                    * np.sin(angle)
                )

                col = (
                    center_col
                    + candidate_radius
                    * np.cos(angle)
                )

                if (
                    row < 1
                    or row >= rows - 1
                    or col < 1
                    or col >= cols - 1
                ):
                    continue

                test_radius = candidate_radius
                break

            radii.append(
                test_radius
            )

        if not radii:
            return 0.0

        mean_radius = float(
            np.mean(radii)
        )

        std_radius = float(
            np.std(radii)
        )

        if mean_radius <= 0:
            return 0.0

        circularity = (
            1.0
            -
            std_radius / mean_radius
        )

        return float(
            np.clip(
                circularity,
                0.0,
                1.0,
            )
        )